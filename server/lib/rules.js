/** Splicing.result_of: result seed id, or -1 (negative, same, non-seed or unknown pair). */
function spliceResult(a, b) {
  if (a < 0 || b < 0 || a === b || !isSeed(a) || !isSeed(b)) return -1;
  return SPLICES[spliceKey(a, b)] ?? -1;
}
